import { readdir } from "node:fs/promises";
import { extname, join, normalize, relative, resolve } from "node:path";
import type { Tab } from "../../sdk/ts/src/index.ts";
import { benchmarkSources, sourceCheck } from "./sources.ts";
import type {
  BenchmarkDoctorReport,
  BenchmarkTask,
} from "./types.ts";

const MIME_TYPES: Record<string, string> = {
  ".css": "text/css; charset=utf-8",
  ".gif": "image/gif",
  ".html": "text/html; charset=utf-8",
  ".jpeg": "image/jpeg",
  ".jpg": "image/jpeg",
  ".js": "text/javascript; charset=utf-8",
  ".json": "application/json; charset=utf-8",
  ".png": "image/png",
  ".svg": "image/svg+xml",
};

export type MiniWobServer = {
  origin: string;
  taskUrl(taskId: string): string;
  stop(): void;
};

export type MiniWobEpisodeResult = {
  done: boolean;
  reward: number;
  rawReward: number;
  reason: string | null;
  episodeId: number;
  passed: boolean;
};

export type MiniWobEpisodeOptions = {
  seed: number;
  episodeMaxTimeMs?: number;
  removeHumanDisplay?: boolean;
};

export const BROWSERGYM_MINIWOB_EPISODE_MAX_TIME_MS = 1_000_000;

export async function miniWobDoctor(): Promise<BenchmarkDoctorReport> {
  const source = benchmarkSources().miniwob;
  const checks = [
    await sourceCheck("MiniWoB++ source", source, "miniwob/html/core/core.js"),
    await sourceCheck("MiniWoB++ tasks", source, "miniwob/html/miniwob/click-test.html"),
  ];
  return { ready: checks.every((check) => check.status === "ready"), checks };
}

export async function listMiniWobTasks(): Promise<BenchmarkTask[]> {
  const source = benchmarkSources().miniwob;
  const taskDirectory = join(source, "miniwob/html/miniwob");
  const files = (await readdir(taskDirectory))
    .filter((file) => file.endsWith(".html"))
    .sort();
  return files.map((file) => ({
    suite: "miniwob++",
    id: file.slice(0, -".html".length),
    intent: "Generated by the official MiniWoB++ page when the episode starts",
    sites: ["miniwob++"],
    startUrls: [`/miniwob/${file}`],
    sourceFile: join(taskDirectory, file),
    inputImages: [],
    difficulty: {},
    evaluation: {
      owner: "official-page",
      globals: [
        "WOB_DONE_GLOBAL",
        "WOB_REWARD_GLOBAL",
        "WOB_RAW_REWARD_GLOBAL",
        "WOB_REWARD_REASON",
      ],
    },
  }));
}

export async function miniWobTask(taskId: string): Promise<BenchmarkTask> {
  const task = (await listMiniWobTasks()).find((candidate) => candidate.id === taskId);
  if (!task) {
    throw new Error(`unknown MiniWoB++ task: ${taskId}`);
  }
  return task;
}

export function startMiniWobServer(port = 0): MiniWobServer {
  const htmlRoot = resolve(benchmarkSources().miniwob, "miniwob/html");
  const server = Bun.serve({
    hostname: "127.0.0.1",
    port,
    async fetch(request) {
      if (request.method !== "GET" && request.method !== "HEAD") {
        return new Response("method not allowed", { status: 405 });
      }
      const url = new URL(request.url);
      const decoded = decodeURIComponent(url.pathname);
      const relativePath = decoded === "/" ? "miniwob/click-test.html" : decoded.slice(1);
      const filePath = resolve(htmlRoot, normalize(relativePath));
      const pathWithinRoot = relative(htmlRoot, filePath);
      if (pathWithinRoot.startsWith("..") || pathWithinRoot.includes("../")) {
        return new Response("not found", { status: 404 });
      }
      const file = Bun.file(filePath);
      if (!(await file.exists())) {
        return new Response("not found", { status: 404 });
      }
      const headers = {
        "content-type": MIME_TYPES[extname(filePath).toLowerCase()] ?? "application/octet-stream",
        "cache-control": "no-store",
      };
      return request.method === "HEAD"
        ? new Response(null, { headers })
        : new Response(file, { headers });
    },
  });
  const origin = `http://${server.hostname}:${server.port}`;
  return {
    origin,
    taskUrl(taskId) {
      if (!/^[a-z0-9-]+$/.test(taskId)) {
        throw new Error(`invalid MiniWoB++ task id: ${taskId}`);
      }
      return `${origin}/miniwob/${taskId}.html`;
    },
    stop() {
      server.stop(true);
    },
  };
}

export async function beginMiniWobEpisode(
  tab: Tab,
  taskUrl: string,
  options: MiniWobEpisodeOptions = { seed: 0 },
): Promise<string> {
  await prepareMiniWobEpisode(tab, taskUrl);
  const episodeMaxTimeMs = options.episodeMaxTimeMs ?? BROWSERGYM_MINIWOB_EPISODE_MAX_TIME_MS;
  await tab.evaluate(({ seed, episodeMaxTimeMs, removeHumanDisplay }) => {
    const state = globalThis as typeof globalThis & {
      core: {
        EPISODE_MAX_TIME: number;
        clearTimer(): void;
        canvasDrawClick: EventListener;
        createDisplay(): void;
        endEpisode(reward: number, timeProportional?: boolean, reason?: string): void;
        getUtterance(): string | { utterance: string };
        startEpisodeReal(): void;
      };
      Math: typeof Math & { seedrandom(seed: number): void };
    };
    const core = state.core;
    if (removeHumanDisplay) {
      const displayIds = ["reward-display", "click-canvas", "sync-task-cover"];
      const displayElements = new Map<string, HTMLElement>();
      let hiddenQuery: Node | null = null;
      const removeDisplay = () => {
        core.clearTimer();
        document.body.removeEventListener("click", core.canvasDrawClick);
        const query = document.getElementById("query");
        if (!query) throw new Error("MiniWoB query display is missing");
        hiddenQuery = query.cloneNode(true);
        query.innerHTML = "";
        for (const id of displayIds) {
          const element = document.getElementById(id);
          if (!element) throw new Error(`MiniWoB display ${id} is missing`);
          element.remove();
          displayElements.set(id, element);
        }
      };
      const bringBackDisplay = () => {
        const query = document.getElementById("query");
        if (!query || !hiddenQuery) throw new Error("MiniWoB hidden query display is missing");
        query.innerHTML = (hiddenQuery as HTMLElement).innerHTML;
        for (const element of displayElements.values()) document.body.append(element);
        core.createDisplay();
      };
      const legacyEndEpisode = core.endEpisode.bind(core);
      const legacyGetUtterance = core.getUtterance.bind(core);
      const legacyStartEpisode = core.startEpisodeReal.bind(core);
      core.getUtterance = () => {
        bringBackDisplay();
        const utterance = legacyGetUtterance();
        removeDisplay();
        return utterance;
      };
      core.endEpisode = (reward, timeProportional, reason) => {
        bringBackDisplay();
        legacyEndEpisode(reward, timeProportional, reason);
        removeDisplay();
      };
      core.startEpisodeReal = () => {
        bringBackDisplay();
        legacyStartEpisode();
        removeDisplay();
      };
      removeDisplay();
    }
    state.Math.seedrandom(seed);
    core.EPISODE_MAX_TIME = episodeMaxTimeMs;
    core.startEpisodeReal();
  }, {
    seed: options.seed,
    episodeMaxTimeMs,
    removeHumanDisplay: options.removeHumanDisplay ?? true,
  });
  const deadline = Date.now() + 5_000;
  while (Date.now() < deadline) {
    const ready = await tab.evaluate(() => (
      globalThis as typeof globalThis & { WOB_TASK_READY?: boolean }
    ).WOB_TASK_READY === true);
    if (ready) break;
    await Bun.sleep(20);
  }
  const goal = await tab.evaluate(() => {
    const core = (globalThis as typeof globalThis & {
      core: { getUtterance(): string | { utterance: string } };
    }).core;
    const value = core.getUtterance();
    return typeof value === "string" ? value : value.utterance;
  });
  return goal.trim();
}

export async function prepareMiniWobEpisode(tab: Tab, taskUrl: string): Promise<void> {
  await tab.navigate(taskUrl, { waitUntil: "load", timeoutMs: 30_000 });
  await tab.waitFor({ selector: "#sync-task-cover", state: "visible", timeoutMs: 10_000 });
}

export async function readMiniWobResult(tab: Tab): Promise<MiniWobEpisodeResult> {
  const result = await tab.evaluate(() => {
    const state = globalThis as typeof globalThis & {
      WOB_DONE_GLOBAL?: boolean;
      WOB_REWARD_GLOBAL?: number;
      WOB_RAW_REWARD_GLOBAL?: number;
      WOB_REWARD_REASON?: string | null;
      WOB_EPISODE_ID?: number;
    };
    return {
      done: state.WOB_DONE_GLOBAL === true,
      reward: state.WOB_REWARD_GLOBAL ?? 0,
      rawReward: state.WOB_RAW_REWARD_GLOBAL ?? 0,
      reason: state.WOB_REWARD_REASON ?? null,
      episodeId: state.WOB_EPISODE_ID ?? 0,
    };
  });
  return { ...result, passed: result.done && result.rawReward > 0 };
}
